/**
 * 归一化文本的坐标系契约。
 *
 * @packageDocumentation
 */

/**
 * 归一化文本 + 下标映射。
 *
 * 这是整个归一化体系的坐标系基础：**任何改变长度的处理都必须携带映射**，
 * 否则拿不回原文坐标。
 *
 * @remarks
 * **这个类型为什么存在**：字符串归一化（`toLowerCase`、NFKC、去掉标点……）
 * 是无数库都会做的事，但**没有哪个库在归一化的同时告诉你
 * "第 i 个归一化后的字符对应原文的哪一段"**。
 * 而搜索高亮、引用定位、文本 diff 恰恰都需要这个信息。
 *
 * 不变量（由属性测试覆盖）：
 * 1. `map` 单调不减
 * 2. `src.slice(map[i], mapEnd[i])` 归一化后 === `text[i]`
 */
export interface NormalizedText {
  /** 归一化后的文本 */
  text: string;

  /**
   * `map[i]` = 第 i 个字符在最原始输入（md 源码）中的**起始**下标。
   * 末尾还有一个哨兵元素，表示整个输入的结束位置。
   */
  map: number[];

  /**
   * `mapEnd[i]` = 第 i 个字符的**结束**下标（不含），
   * 即 `length = mapEnd[末字符] - map[首字符]`。
   *
   * @remarks
   * **不可由 `map[i + 1]` 推算**：转义（`\*` → `*`）与实体（`&amp;` → `&`）
   * 会让一个可见字符横跨多个源码字符。这是最容易出错的地方。
   */
  mapEnd?: number[];

  /**
   * 反向映射：当前下标 → 上一层输入的下标。
   *
   * @remarks
   * 链式处理（md 摊平 → 归一化）时用于把坐标换算回中间层。
   * 必须**跨阶段复合** —— 每个阶段只知道"指向本阶段输入"，
   * 直接覆盖会丢失前面阶段的长度变化。
   */
  back?: number[];
}
